import api from "../lib/api";

// ---------------------------------------------------------------------------
// Populated references
// ---------------------------------------------------------------------------

/**
 * Populated User reference.
 *
 * GET /students populates only `email`.
 * Other reads populate more (name, role, profileImage) — those fields are
 * marked optional here so both shapes are valid.
 */
export interface StudentUser {
  _id: string;
  email?: string;
  name?: string;
  role?: "admin" | "staff" | "student";
  profileImage?: string;
}

/**
 * Populated Course reference.
 *
 * GET /students populates only `name`.
 * GET /students/:id populates the full document minus `description`.
 * `courseId` may also be null when the referenced Course no longer exists.
 */
export interface Course {
  _id: string;
  name?: string;
  courseCode?: string;
  level?: string;
  duration?: string;
  department?: string;
}

// ---------------------------------------------------------------------------
// Sub-documents
// ---------------------------------------------------------------------------

export interface AddressDetail {
  address: string;
  constituency: string;
  county: string;
  postalCode: string;
}

export interface Address {
  permanent: AddressDetail;
  present: AddressDetail;
}

export interface Contact {
  email: string;
  phoneNumber: string;
}

export interface FullName {
  firstName: string;
  lastName: string;
  middleName: string;
}

export interface Identification {
  bloodGroup: string;
  idNumber: string;
  passportNumber: string;
}

/**
 * Student course enrollment.
 *
 * - `_id` is the enrollment subdocument id (StudentCourse._id), generated by
 *   the backend. Always present on responses from the current backend; kept
 *   optional so the type stays compatible with any legacy records that predate
 *   the schema fix.
 * - `courseId` is a populated Course, a raw ObjectId string, or null when the
 *   referenced Course no longer exists.
 * - `admissionNumber` is always generated by the backend — never sent from the
 *   client on create or add-enrollment.
 */
export interface StudentCourse {
  _id?: string;
  admissionNumber: string;
  courseId: Course | string | null;
  dateOfAdmission: string;
  dateOfCompletion?: string;
}

// ---------------------------------------------------------------------------
// Student entity
// ---------------------------------------------------------------------------

export interface Student {
  _id: string;

  userId?: StudentUser | string;

  fullName: FullName;

  gender: "Male" | "Female" | "Other";

  dateOfBirth: string;

  nationality: string;

  maritalStatus: "Single" | "Married" | "Divorced" | "Widowed";

  occupation: string;

  physicalDisability: string;

  religion?: string;

  contact: Contact;

  addresses: Address;

  identification: Identification;

  courses: StudentCourse[];

  createdAt?: string;
  updatedAt?: string;
  __v?: number;
}

// ---------------------------------------------------------------------------
// Stats / aggregate types
// ---------------------------------------------------------------------------

/**
 * High-level student population statistics.
 *
 * GET /students/stats/overview
 */
export interface StudentOverviewStats {
  totalStudents: number;
  totalEnrollments: number;
  activeEnrollments: number;
  completedEnrollments: number;
  genderBreakdown: Array<{ gender: string; count: number }>;
}

/**
 * Per-course enrollment statistics.
 *
 * GET /students/stats/courses
 */
export interface CourseEnrollmentStat {
  courseId: string;
  courseName: string;
  courseCode: string;
  totalEnrollments: number;
  activeEnrollments: number;
  completedEnrollments: number;
  uniqueStudents: number;
}

/**
 * Admission trend entry (one point per year suffix).
 *
 * GET /students/stats/admissions
 */
export interface AdmissionTrendStat {
  year: string;
  admissions: number;
}

/**
 * Deep-dive statistics for a single course.
 *
 * GET /students/stats/courses/:courseId
 */
export interface CourseStats {
  courseId: string;
  courseName: string;
  courseCode: string;
  totalEnrollments: number;
  activeEnrollments: number;
  completedEnrollments: number;
  genderBreakdown: Array<{ gender: string; count: number }>;
  admissionsByYear: Array<{ year: string; count: number }>;
}

// ---------------------------------------------------------------------------
// Create / update DTOs
// ---------------------------------------------------------------------------

/**
 * Course enrollment payload used when creating a student.
 *
 * `admissionNumber` is intentionally omitted — it is generated by the backend.
 */
export interface StudentCourseDto {
  courseId: string;
  dateOfAdmission: string;
  dateOfCompletion?: string;
}

export interface CreateStudentDto {
  userId?: string;

  fullName: FullName;

  gender: "Male" | "Female" | "Other";

  dateOfBirth: string;

  nationality: string;

  maritalStatus: "Single" | "Married" | "Divorced" | "Widowed";

  occupation: string;

  physicalDisability: string;

  religion?: string;

  contact: Contact;

  addresses: Address;

  identification: Identification;

  courses: StudentCourseDto[];
}

export type UpdateStudentDto = Partial<CreateStudentDto>;

// ---------------------------------------------------------------------------
// Enrollment management DTOs
// ---------------------------------------------------------------------------

/**
 * Add one enrollment to an existing student.
 *
 * POST /students/:id/enrollments
 *
 * `courseId` here is the **Course** `_id` — no enrollment subdocument
 * exists yet. The backend generates:
 *   - the enrollment's StudentCourse._id
 *   - the admission number
 */
export interface AddEnrollmentDto {
  /**
   * MongoDB Course ObjectId.
   */
  courseId: string;

  dateOfAdmission: string;

  dateOfCompletion?: string;
}

/**
 * Manual admission number reassignment payload.
 *
 * PATCH /students/:id/admission-number
 *
 * Must match the backend regex:
 *   ATI/<COURSE_CODE>/<INDEX>/<YYY>
 * e.g. ATI/AD/0001/025
 */
export interface UpdateAdmissionNumberDto {
  /**
   * `_id` of the entry inside `student.courses` to re-label.
   */
  courseId: string;

  admissionNumber: string;
}

/**
 * Edit one enrollment row in place.
 *
 * PATCH /students/:id/enrollment
 *
 * - Omitted keys are left untouched.
 * - Pass `null` for a date to clear it.
 * - `courseId` identifies which entry inside `student.courses` to edit.
 */
export interface UpdateEnrollmentDto {
  /**
   * `_id` of the entry inside `student.courses` to edit.
   */
  courseId: string;

  /**
   * Optional — omit to leave the admission number unchanged.
   */
  admissionNumber?: string;

  /**
   * Optional — ISO date string to set, `null` to clear,
   * or omit to leave unchanged.
   */
  dateOfAdmission?: string | null;

  /**
   * Optional — ISO date string to set, `null` to clear,
   * or omit to leave unchanged.
   */
  dateOfCompletion?: string | null;
}

// ---------------------------------------------------------------------------
// API client
// ---------------------------------------------------------------------------

export const studentApi = {
  /**
   * Create a student.
   *
   * POST /students
   */
  create(data: CreateStudentDto) {
    return api.post<Student>("/students", data);
  },

  /**
   * Get all students.
   *
   * GET /students
   */
  getAll() {
    return api.get<Student[]>("/students");
  },

  /**
   * Get a single student by Student ObjectId.
   *
   * GET /students/:id
   */
  getById(id: string) {
    return api.get<Student>(`/students/${id}`);
  },

  /**
   * Get student profile by associated User ID.
   *
   * GET /students/user/:userId
   */
  getByUserId(userId: string) {
    return api.get<Student>(`/students/user/${userId}`);
  },

  /**
   * Update an existing student record.
   *
   * PATCH /students/:id
   */
  update(id: string, data: UpdateStudentDto) {
    return api.patch<Student>(`/students/${id}`, data);
  },

  /**
   * Add one enrollment to an existing student.
   *
   * POST /students/:id/enrollments
   *
   * `data.courseId` is the **Course** `_id`. The backend generates the
   * enrollment subdocument `_id` and the admission number.
   */
  addEnrollment(id: string, data: AddEnrollmentDto) {
    return api.post<Student>(`/students/${id}/enrollments`, data);
  },

  /**
   * Remove one enrollment from a student.
   *
   * DELETE /students/:id/enrollments/:enrollmentId
   *
   * `enrollmentId` is the **StudentCourse** `_id` (enrollment subdocument id),
   * NOT the Course `_id`.
   */
  removeEnrollment(id: string, enrollmentId: string) {
    return api.delete<Student>(
      `/students/${id}/enrollments/${enrollmentId}`,
    );
  },

  /**
   * Manually reassign an admission number to a student's course entry.
   *
   * PATCH /students/:id/admission-number
   */
  updateAdmissionNumber(id: string, data: UpdateAdmissionNumberDto) {
    return api.patch<Student>(`/students/${id}/admission-number`, data);
  },

  /**
   * Edit one enrollment row — admission number and/or dates.
   *
   * PATCH /students/:id/enrollment
   */
  updateEnrollment(id: string, data: UpdateEnrollmentDto) {
    return api.patch<Student>(`/students/${id}/enrollment`, data);
  },

  /**
   * Remove a student record.
   *
   * DELETE /students/:id
   */
  delete(id: string) {
    return api.delete<{ message: string }>(`/students/${id}`);
  },

  // -------------------------------------------------------------------------
  // Stats / aggregates
  // -------------------------------------------------------------------------

  /**
   * Get high-level student population statistics.
   *
   * GET /students/stats/overview
   */
  getOverviewStats() {
    return api.get<StudentOverviewStats>("/students/stats/overview");
  },

  /**
   * Get per-course enrollment statistics.
   *
   * GET /students/stats/courses
   */
  getCourseEnrollmentStats() {
    return api.get<CourseEnrollmentStat[]>("/students/stats/courses");
  },

  /**
   * Get admission counts grouped by year suffix.
   *
   * GET /students/stats/admissions
   */
  getAdmissionTrendStats() {
    return api.get<AdmissionTrendStat[]>("/students/stats/admissions");
  },

  /**
   * Get deep-dive statistics for a single course.
   *
   * GET /students/stats/courses/:courseId
   */
  getCourseStats(courseId: string) {
    return api.get<CourseStats>(`/students/stats/courses/${courseId}`);
  },
};
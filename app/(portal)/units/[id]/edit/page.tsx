"use client";

import { useEffect, useState } from "react";
import { useParams, useRouter, useSearchParams } from "next/navigation";
import Link from "next/link";
import {
    ArrowLeft,
    BookOpen,
    AlertCircle,
    CheckCircle2,
    Loader2,
    GraduationCap,
    FileText,
    Tag,
    Sparkles,
    RefreshCw,
    X,
    Layers,
    PlusCircle,
} from "lucide-react";

import { Unit, unitApi, UpdateUnitDto, UnitType } from "@/app/types/units";
import { Course, courseApi } from "@/app/types/courses";
import SelectCourse from "@/app/(portal)/courses/selectCourse";
import { generateUnitCode } from "../../new/generateCode";

export default function EditUnitPage() {
    const params = useParams();
    const searchParams = useSearchParams();
    const router = useRouter();

    const id = params?.id as string;
    // Optional courseId parameter passed via search query (e.g., /units/[id]/edit?courseId=123)
    const fixedCourseId = searchParams.get("courseId");

    // Unit & Data States
    const [unit, setUnit] = useState<Unit | null>(null);
    const [courses, setCourses] = useState<Course[]>([]);
    const [loading, setLoading] = useState<boolean>(true);
    const [loadingCourses, setLoadingCourses] = useState<boolean>(false);
    const [error, setError] = useState<string | null>(null);

    // Edit State
    const [editFormData, setEditFormData] = useState<UpdateUnitDto>({});
    const [isUpdating, setIsUpdating] = useState<boolean>(false);
    const [actionType, setActionType] = useState<"save" | "saveAndContinue" | null>(null);
    const [generatingCode, setGeneratingCode] = useState<boolean>(false);
    const [isCodeAutoGenerated, setIsCodeAutoGenerated] = useState<boolean>(false);

    // Load Unit + Courses on mount
    useEffect(() => {
        if (!id) return;

        async function fetchData() {
            try {
                setLoading(true);
                setLoadingCourses(true);

                const [unitRes, coursesRes] = await Promise.all([
                    unitApi.getById(id),
                    courseApi.getAll(),
                ]);

                const data = unitRes.data;
                setUnit(data);
                
                const targetCourseId =
                    fixedCourseId ||
                    (typeof data.courseId === "string"
                        ? data.courseId
                        : data.courseId?._id);

                populateEditForm(data, targetCourseId);
                setCourses(coursesRes.data || []);
            } catch (err: any) {
                console.error("Failed to fetch data:", err);
                setError(err.response?.data?.message || "Failed to load unit details.");
            } finally {
                setLoading(false);
                setLoadingCourses(false);
            }
        }

        fetchData();
    }, [id, fixedCourseId]);

    const populateEditForm = (unitData: Unit, preferredCourseId?: string) => {
        setEditFormData({
            name: unitData.name,
            code: unitData.code,
            description: unitData.description || "",
            type: unitData.type || ("core" as UnitType),
            optionalUnit: unitData.optionalUnit || false,
            courseId:
                preferredCourseId ||
                (typeof unitData.courseId === "string"
                    ? unitData.courseId
                    : unitData.courseId?._id),
        });
        setIsCodeAutoGenerated(false);
    };

    // Code Generator Helper
    const triggerCodeGeneration = async (course: Course) => {
        try {
            setGeneratingCode(true);
            setError(null);

            const generatedCode = await generateUnitCode(course);

            setEditFormData((prev) => ({
                ...prev,
                code: generatedCode,
            }));
            setIsCodeAutoGenerated(true);
        } catch (err: any) {
            setError(err.message || "Failed to auto-generate unit code.");
        } finally {
            setGeneratingCode(false);
        }
    };

    const handleCourseChange = async (courseId: string, selectedCourse?: Course) => {
        // If a course ID is explicitly locked to this route context, prevent changes
        if (fixedCourseId) return;

        setEditFormData((prev) => ({
            ...prev,
            courseId,
        }));

        if (!selectedCourse) return;

        if (isCodeAutoGenerated || !editFormData.code?.trim()) {
            await triggerCodeGeneration(selectedCourse);
        }
    };

    const handleAutoGenerateCode = async () => {
        const activeCourseId = fixedCourseId || editFormData.courseId;
        if (!activeCourseId) {
            setError("Please select an Associated Course first to generate a code.");
            return;
        }

        const selectedCourse = courses.find((c) => c._id === activeCourseId);
        if (!selectedCourse) {
            setError("Selected course details could not be found.");
            return;
        }

        await triggerCodeGeneration(selectedCourse);
    };

    const handleChange = (
        e: React.ChangeEvent<
            HTMLInputElement | HTMLTextAreaElement | HTMLSelectElement
        >
    ) => {
        const { name, value } = e.target;

        if (name === "code") {
            setIsCodeAutoGenerated(false);
        }

        setEditFormData((prev) => ({
            ...prev,
            [name]: value,
        }));
    };

    const handleCheckboxChange = (e: React.ChangeEvent<HTMLInputElement>) => {
        const { name, checked } = e.target;
        setEditFormData((prev) => ({
            ...prev,
            [name]: checked,
        }));
    };

    const handleUpdate = async (e: React.FormEvent, continueAdding: boolean = false) => {
        e.preventDefault();
        if (!id) return;

        setError(null);

        const activeCourseId = fixedCourseId || editFormData.courseId;

        if (!activeCourseId) {
            setError("Please select a Course for this unit.");
            return;
        }

        if (!editFormData.code?.trim()) {
            setError("Unit Code is required.");
            return;
        }

        if (!editFormData.name?.trim()) {
            setError("Unit Name is required.");
            return;
        }

        try {
            setIsUpdating(true);
            setActionType(continueAdding ? "saveAndContinue" : "save");

            const payload: UpdateUnitDto = {
                name: editFormData.name.trim(),
                code: editFormData.code.trim().toUpperCase(),
                courseId: activeCourseId,
                description: editFormData.description?.trim() || undefined,
                type: editFormData.type,
                optionalUnit: editFormData.optionalUnit,
            };

            await unitApi.update(id, payload);

            if (continueAdding) {
                // Navigate to unit creation page with the fixed course preset
                router.push(`/units/new?courseId=${activeCourseId}`);
            } else {
                // If scoped to a specific course, exit directly to that course's details page
                if (fixedCourseId) {
                    router.push(`/courses/${fixedCourseId}`);
                } else {
                    router.push(`/units/${id}`);
                }
                router.refresh();
            }
        } catch (err: any) {
            console.error("Failed to update unit:", err);
            setError(
                err.response?.data?.message ||
                    "Failed to update unit. Please check your inputs and try again."
            );
        } finally {
            setIsUpdating(false);
            setActionType(null);
        }
    };

    const backPath = fixedCourseId ? `/courses/${fixedCourseId}` : `/units/${id}`;

    if (loading) {
        return (
            <div className="flex flex-col items-center justify-center min-h-100 gap-3">
                <Loader2 className="w-8 h-8 animate-spin text-[#082B66] dark:text-orange-400" />
                <p className="text-sm font-medium text-zinc-500 dark:text-zinc-400">Loading unit details...</p>
            </div>
        );
    }

    if (error && !unit) {
        return (
            <div className="p-4 sm:p-6 lg:p-8 max-w-400 mx-auto space-y-4">
                <Link
                    href={backPath}
                    className="inline-flex items-center gap-1.5 text-xs font-medium text-zinc-500 hover:text-zinc-800 transition-colors dark:text-zinc-400 dark:hover:text-zinc-200"
                >
                    <ArrowLeft className="w-3.5 h-3.5" /> Back
                </Link>
                <div className="p-4 bg-red-50 border border-red-200 text-red-700 rounded-sm flex items-start gap-3 shadow-sm dark:bg-red-950/30 dark:border-red-900/50 dark:text-red-400">
                    <AlertCircle className="w-5 h-5 shrink-0 text-red-500 mt-0.5 dark:text-red-400" />
                    <p className="text-sm font-medium">{error || "Unit not found."}</p>
                </div>
            </div>
        );
    }

    return (
        <div className="p-4 sm:p-6 lg:p-8 max-w-400 mx-auto space-y-6">
            {/* Navigation & Header */}
            <div>
                <Link
                    href={backPath}
                    className="inline-flex items-center gap-1.5 text-xs font-medium text-zinc-500 hover:text-zinc-800 transition-colors mb-3 dark:text-zinc-400 dark:hover:text-zinc-200"
                >
                    <ArrowLeft className="w-3.5 h-3.5" /> {fixedCourseId ? "Back to Course" : "Back to Unit"}
                </Link>

                <div className="flex items-center gap-3">
                    <div className="p-2.5 bg-[#082B66]/10 text-[#082B66] rounded-sm border border-[#082B66]/20 shadow-sm dark:bg-orange-400/10 dark:text-orange-400 dark:border-orange-400/20">
                        <BookOpen className="w-6 h-6" />
                    </div>
                    <div>
                        <h1 className="text-xl sm:text-2xl font-bold text-zinc-900 dark:text-white">
                            Edit Unit
                        </h1>
                        <p className="text-xs sm:text-sm text-zinc-500 dark:text-zinc-400">
                            Updating{" "}
                            <span className="font-medium text-zinc-700 dark:text-zinc-300">{unit?.name}</span>{" "}
                            <span className="font-mono">({unit?.code})</span>
                        </p>
                    </div>
                </div>
            </div>

            {/* Error Notification */}
            {error && (
                <div className="p-4 bg-red-50 border border-red-200 text-red-700 rounded-sm flex items-start gap-3 shadow-sm animate-in fade-in duration-200 dark:bg-red-950/30 dark:border-red-900/50 dark:text-red-400">
                    <AlertCircle className="w-5 h-5 shrink-0 text-red-500 mt-0.5 dark:text-red-400" />
                    <p className="text-sm font-medium">{error}</p>
                </div>
            )}

            {/* Edit Form */}
            <form
                onSubmit={(e) => handleUpdate(e, false)}
                className="bg-white border border-zinc-200 rounded-sm shadow-sm p-4 sm:p-6 lg:p-8 space-y-6 dark:bg-zinc-900 dark:border-zinc-800"
            >
                <div className="flex items-center justify-between pb-4 border-b border-zinc-100 dark:border-zinc-800">
                    <h2 className="text-base font-bold text-zinc-900 flex items-center gap-2 dark:text-white">
                        <Sparkles className="w-4 h-4 text-[#082B66] dark:text-orange-400" />
                        Unit Details
                    </h2>
                    <Link
                        href={backPath}
                        className="text-zinc-400 hover:text-zinc-600 p-1 rounded-sm hover:bg-zinc-100 transition-colors dark:text-zinc-500 dark:hover:text-zinc-300 dark:hover:bg-zinc-800"
                        aria-label="Close edit"
                    >
                        <X className="w-5 h-5" />
                    </Link>
                </div>

                {/* Associated Course */}
                <div className="space-y-1.5">
                    <label
                        htmlFor="courseId"
                        className="text-xs font-semibold text-zinc-700 uppercase tracking-wider flex items-center gap-1.5 dark:text-zinc-300"
                    >
                        <GraduationCap className="w-4 h-4 text-zinc-500 dark:text-zinc-400" />
                        Associated Course <span className="text-red-500">*</span>
                    </label>
                    <SelectCourse
                        value={fixedCourseId || editFormData.courseId || ""}
                        onChange={handleCourseChange}
                        courses={courses}
                        loading={loadingCourses}
                        disabled={Boolean(fixedCourseId)}
                        required
                        placeholder="Search or select a course..."
                    />
                    {fixedCourseId && (
                        <p className="text-[11px] text-amber-600 dark:text-amber-400">
                            Course assignment is locked because this unit is being managed from within its specific course context.
                        </p>
                    )}
                </div>

                {/* Unit Code & Unit Name */}
                <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
                    <div className="space-y-1.5">
                        <div className="flex items-center justify-between">
                            <label
                                htmlFor="code"
                                className="block text-xs font-semibold text-zinc-700 uppercase tracking-wider dark:text-zinc-300"
                            >
                                Unit Code <span className="text-red-500">*</span>
                            </label>
                            {isCodeAutoGenerated && (
                                <span className="text-[10px] font-medium text-[#082B66] bg-[#082B66]/10 px-2 py-0.5 rounded-sm border border-[#082B66]/20 flex items-center gap-1 dark:text-orange-400 dark:bg-orange-400/10 dark:border-orange-400/20">
                                    <Sparkles className="w-2.5 h-2.5" /> Auto-Synced
                                </span>
                            )}
                        </div>
                        <div className="space-y-2">
                            <input
                                id="code"
                                name="code"
                                type="text"
                                required
                                placeholder="e.g. CISA001"
                                value={editFormData.code || ""}
                                onChange={handleChange}
                                className="w-full px-3.5 py-2.5 border border-zinc-300 rounded-sm font-mono text-sm uppercase text-zinc-900 focus:ring-2 focus:ring-[#082B66] focus:border-[#082B66] focus:outline-none transition-all shadow-sm dark:border-zinc-700 dark:bg-zinc-800 dark:text-white dark:focus:ring-orange-400 dark:focus:border-orange-400"
                            />
                            <button
                                type="button"
                                onClick={handleAutoGenerateCode}
                                disabled={(!fixedCourseId && !editFormData.courseId) || generatingCode}
                                className="w-full py-2 px-3 bg-linear-to-r from-[#082B66]/5 to-[#082B66]/10 hover:from-[#082B66]/10 hover:to-[#082B66]/15 border border-[#082B66]/20 rounded-sm text-xs font-semibold text-[#082B66] flex items-center justify-center gap-1.5 transition-all shadow-xs disabled:opacity-50 disabled:cursor-not-allowed active:scale-[0.99] dark:from-orange-400/10 dark:to-orange-400/5 dark:hover:from-orange-400/15 dark:hover:to-orange-400/10 dark:border-orange-400/20 dark:text-orange-400"
                            >
                                {generatingCode ? (
                                    <>
                                        <Loader2 className="w-3.5 h-3.5 animate-spin text-[#082B66] dark:text-orange-400" />
                                        Generating...
                                    </>
                                ) : isCodeAutoGenerated ? (
                                    <>
                                        <RefreshCw className="w-3.5 h-3.5 text-[#082B66] dark:text-orange-400" />
                                        Re-Generate Code
                                    </>
                                ) : (
                                    <>
                                        <Sparkles className="w-3.5 h-3.5 text-[#082B66] dark:text-orange-400" />
                                        Auto-Generate Code
                                    </>
                                )}
                            </button>
                        </div>
                    </div>

                    {/* Unit Name */}
                    <div className="md:col-span-2 space-y-1.5">
                        <label
                            htmlFor="name"
                            className="block text-xs font-semibold text-zinc-700 uppercase tracking-wider dark:text-zinc-300"
                        >
                            Unit Name <span className="text-red-500">*</span>
                        </label>
                        <input
                            id="name"
                            name="name"
                            type="text"
                            required
                            placeholder="e.g. Introduction to Computer Science"
                            value={editFormData.name || ""}
                            onChange={handleChange}
                            className="w-full px-3.5 py-2.5 border border-zinc-300 rounded-sm text-sm text-zinc-900 focus:ring-2 focus:ring-[#082B66] focus:border-[#082B66] focus:outline-none transition-all shadow-sm dark:border-zinc-700 dark:bg-zinc-800 dark:text-white dark:focus:ring-orange-400 dark:focus:border-orange-400"
                        />
                    </div>
                </div>

                {/* Unit Type Selection */}
                <div className="space-y-1.5">
                    <label
                        htmlFor="type"
                        className="text-xs font-semibold text-zinc-700 uppercase tracking-wider flex items-center gap-1.5 dark:text-zinc-300"
                    >
                        <Layers className="w-4 h-4 text-zinc-500 dark:text-zinc-400" />
                        Unit Classification Type
                    </label>
                    <select
                        id="type"
                        name="type"
                        value={editFormData.type || ("core" as UnitType)}
                        onChange={handleChange}
                        className="w-full px-3.5 py-2.5 border border-zinc-300 rounded-sm text-sm text-zinc-900 bg-white focus:ring-2 focus:ring-[#082B66] focus:border-[#082B66] focus:outline-none transition-all shadow-sm capitalize dark:border-zinc-700 dark:bg-zinc-800 dark:text-white dark:focus:ring-orange-400 dark:focus:border-orange-400"
                    >
                        {Object.values(UnitType).map((t) => (
                            <option key={t} value={t} className="capitalize">
                                {t.charAt(0).toUpperCase() + t.slice(1)} Unit
                            </option>
                        ))}
                    </select>
                </div>

                {/* Optional Unit Toggle */}
                <div className="p-4 bg-zinc-50 border border-zinc-200 rounded-sm flex items-center justify-between gap-4 dark:bg-zinc-800/50 dark:border-zinc-700">
                    <div className="space-y-0.5">
                        <label
                            htmlFor="optionalUnit"
                            className="text-sm font-semibold text-zinc-800 flex items-center gap-2 cursor-pointer dark:text-zinc-100"
                        >
                            <Tag className="w-4 h-4 text-[#082B66] shrink-0 dark:text-orange-400" />
                            Elective / Optional Unit
                        </label>
                        <p className="text-xs text-zinc-500 dark:text-zinc-400">
                            Mark this unit as optional rather than mandatory core coursework.
                        </p>
                    </div>
                    <input
                        id="optionalUnit"
                        name="optionalUnit"
                        type="checkbox"
                        checked={editFormData.optionalUnit || false}
                        onChange={handleCheckboxChange}
                        className="w-5 h-5 rounded-sm border-zinc-300 accent-[#082B66] focus:ring-[#082B66] cursor-pointer shrink-0 dark:border-zinc-600 dark:accent-orange-400 dark:focus:ring-orange-400"
                    />
                </div>

                {/* Description */}
                <div className="space-y-1.5">
                    <label
                        htmlFor="description"
                        className="text-xs font-semibold text-zinc-700 uppercase tracking-wider flex items-center gap-1.5 dark:text-zinc-300"
                    >
                        <FileText className="w-4 h-4 text-zinc-500 dark:text-zinc-400" />
                        Description
                    </label>
                    <textarea
                        id="description"
                        name="description"
                        rows={4}
                        placeholder="Brief overview of learning outcomes, topics, or requirements for this unit..."
                        value={editFormData.description || ""}
                        onChange={handleChange}
                        className="w-full px-3.5 py-2.5 border border-zinc-300 rounded-sm text-sm text-zinc-900 focus:ring-2 focus:ring-[#082B66] focus:border-[#082B66] focus:outline-none transition-all shadow-sm dark:border-zinc-700 dark:bg-zinc-800 dark:text-white dark:focus:ring-orange-400 dark:focus:border-orange-400"
                    />
                </div>

                {/* Action Buttons */}
                <div className="pt-6 border-t border-zinc-100 flex flex-col sm:flex-row items-center justify-end gap-3 dark:border-zinc-800">
                    <Link
                        href={backPath}
                        className="w-full sm:w-auto text-center px-4 py-2.5 text-sm font-medium text-zinc-600 hover:text-zinc-800 hover:bg-zinc-50 rounded-sm transition-colors dark:text-zinc-300 dark:hover:text-zinc-100 dark:hover:bg-zinc-800"
                    >
                        Cancel
                    </Link>

                    <button
                        type="submit"
                        disabled={isUpdating}
                        className="w-full sm:w-auto flex items-center justify-center gap-2 bg-[#082B66] hover:bg-[#082B66]/90 text-white px-5 py-2.5 rounded-sm text-sm font-semibold transition-all shadow-sm disabled:opacity-50 disabled:cursor-not-allowed dark:bg-orange-400 dark:text-zinc-900 dark:hover:bg-orange-400/90"
                    >
                        {isUpdating && actionType === "save" ? (
                            <>
                                <Loader2 className="w-4 h-4 animate-spin" />
                                Saving...
                            </>
                        ) : (
                            <>
                                <CheckCircle2 className="w-4 h-4" />
                                Save
                            </>
                        )}
                    </button>
                </div>
            </form>
        </div>
    );
}